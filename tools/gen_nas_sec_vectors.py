#!/usr/bin/env python3
"""Generate libs/crypto/tests/nas_sec_vectors.h from TS 33.401 Annex C (128-EEA2 / 128-EIA2 test sets), text
extracted with tools/doc_to_text.py to docs/specs/src/33401-g40.txt. 128-NEA2/NIA2 are identical to EEA2/EIA2.
Used by libs/crypto/tests/test_nas_sec.c.

Only whole-octet data is checked: EEA2 sets whose bit length is not a multiple of 8 are compared on their full
octets; EIA2 sets are used only when the message length is a multiple of 8 bits (sets 2, 5 and 8)."""
import re

text = open("docs/specs/src/33401-g40.txt", encoding="utf8").read()


def section(start_pat, end_pat):
    # use the last occurrence (the first is in the table of contents)
    a = [m for m in re.finditer(start_pat, text)][-1]
    b = re.search(end_pat, text[a.end():])
    return text[a.start():a.end() + (b.start() if b else len(text))]


def sets(block, prefix):
    out = {}
    parts = re.split(r"\n" + re.escape(prefix) + r"\.(\d+)\tTest Set \d+\n", block)
    for i in range(1, len(parts), 2):
        out[int(parts[i])] = parts[i + 1]
    return out


def field(body, label):
    """First hex-format value of a labelled field, joining wrapped continuation lines."""
    lines = body.split("\n")
    for i, l in enumerate(lines):
        m = re.match(r"^\s*" + re.escape(label) + r"\s*=\s*(?:\(hex\))?\s*([0-9a-fA-F ]+)\s*$", l)
        if m and "(bin)" not in l:
            val = m.group(1)
            j = i + 1
            while j < len(lines) and re.match(r"^\s+[0-9a-fA-F ]+\s*$", lines[j]) and "=" not in lines[j]:
                val += lines[j]
                j += 1
            return val.replace(" ", "").lower()
    raise SystemExit(f"field {label!r} not found")


eea = sets(section(r"\nC\.1\t128-EEA2\n", r"\nC\.2\t128-EIA2\n"), "C.1")
eia = sets(section(r"\nC\.2\t128-EIA2\n", r"\nAnnex D"), "C.2")
assert len(eea) == 6 and len(eia) == 8, (sorted(eea), sorted(eia))

out = ["/* @generated by tools/gen_nas_sec_vectors.py from 3GPP TS 33.401 v16.4.0 Annex C. DO NOT EDIT. */",
       "typedef struct { int set; const char *key; unsigned count; unsigned bearer; unsigned dir; unsigned bits; const char *pt, *ct; } eea2_set;",
       "typedef struct { int set; const char *key; unsigned count; unsigned bearer; unsigned dir; const char *msg, *mac; } eia2_set;",
       "/* (set, key, count, bearer, direction, length in bits, plaintext, ciphertext) */",
       "static const eea2_set EEA2[] = {"]
for n in sorted(eea):
    b = eea[n]
    length = int(re.search(r"Length\s*=\s*(\d+) bits", b).group(1))
    out.append(f'    {{{n}, "{field(b, "Key")}", 0x{field(b, "Count")}, 0x{field(b, "Bearer")}, 0x{field(b, "Direction")}, {length}, '
               f'"{field(b, "Plaintext")}", "{field(b, "Ciphertext")}"}},')
out += ["};", "/* (set, integrity key, count, bearer, direction, message, MAC-I) */", "static const eia2_set EIA2[] = {"]
aligned = []
for n in sorted(eia):
    b = eia[n]
    length = int(re.search(r"Length\s*=\s*(\d+) bits", b).group(1))
    if length % 8 == 0:
        aligned.append((n, b, length))
assert [a[0] for a in aligned] == [2, 5, 8], [a[0] for a in aligned]
for n, b, length in aligned:
    msg = field(b, "Message")[: length // 4]
    out.append(f'    {{{n}, "{field(b, "IK")}", 0x{field(b, "Count-I")}, 0x{field(b, "Bearer")}, 0x{field(b, "Direction")}, "{msg}", "{field(b, "MACT")}"}},')
out.append("};")
open("libs/crypto/tests/nas_sec_vectors.h", "w", encoding="utf8", newline="\n").write("\n".join(out) + "\n")
print("generated: 6 EEA2 sets, EIA2 sets", [a[0] for a in aligned])
