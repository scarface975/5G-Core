#!/usr/bin/env python3
"""The API reference (docs/api/README.md): every HTTP route of every function, read from the sources (`g5c_router_route(...)` calls and the UDR's generated operation table), with the
service it belongs to. The reference is generated so that it cannot drift: `python3 tools/docs/gen_api_docs.py --check` (a ctest) fails when the committed file differs from the sources.

    python3 tools/docs/gen_api_docs.py          write docs/api/README.md
    python3 tools/docs/gen_api_docs.py --check  compare only
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
NFS = [("nrf", "NRF", "Nnrf_NFManagement, Nnrf_NFDiscovery, Nnrf_AccessToken (TS 29.510)"), ("scp", "SCP", "indirect communication (TS 29.500 6.10)"),
       ("udr", "UDR", "Nudr_DataRepository (TS 29.504, 29.505, 29.519, 29.511) and the provisioning extensions"), ("udm", "UDM", "Nudm_UEAuthentication, Nudm_SubscriberDataManagement, Nudm_UEContextManagement (TS 29.503) and the admin API"),
       ("ausf", "AUSF", "Nausf_UEAuthentication, Nausf_SoRProtection, Nausf_UPUProtection (TS 29.509)"), ("pcf", "PCF", "Npcf_AMPolicyControl, Npcf_SMPolicyControl, Npcf_PolicyAuthorization (TS 29.507, 29.512, 29.514) and the admin API"),
       ("nssf", "NSSF", "Nnssf_NSSelection, Nnssf_NSSAIAvailability (TS 29.531)"), ("bsf", "BSF", "Nbsf_Management (TS 29.521)"),
       ("nef", "NEF", "northbound APIs for AFs: TrafficInfluence, MonitoringEvent, AsSessionWithQoS (TS 29.522)"), ("smf", "SMF", "Nsmf_PDUSession (TS 29.502)"),
       ("amf", "AMF", "Namf_Communication, Namf_EventExposure and callbacks (TS 29.518)"), ("upf", "UPF", "health and metrics only (the UPF's interfaces are N3 GTP-U, N4 PFCP, N6)")]
COMMON = [("GET", "/health/live", "liveness"), ("GET", "/health/ready", "readiness"), ("GET", "/metrics", "Prometheus metrics")]


def defines(text):
    return {m.group(1): m.group(2) for m in re.finditer(r'#define\s+(\w+)\s+"([^"]*)"', text)}


def resolve(expr, defs):
    out = ""
    for tok in re.findall(r'"([^"]*)"|(\w+)', expr):
        lit, ident = tok
        if lit or (not ident):
            out += lit
        elif ident in defs:
            out += defs[ident]
        else:
            return None
    return out


def routes_of(nf):
    found = set()
    hdefs = {}
    for h in list((ROOT / "nf" / nf / "src").glob("*.h")) + list((ROOT / "nf" / nf / "include").rglob("*.h")):
        hdefs.update(defines(h.read_text(encoding="utf-8", errors="replace")))
    for p in sorted((ROOT / "nf" / nf / "src").glob("*.c")):
        t = p.read_text(encoding="utf-8", errors="replace")
        defs = dict(hdefs)
        defs.update(defines(t))
        defs.update({m.group(1): m.group(2) for m in re.finditer(r"const char \*(\w+)\s*=\s*\"(/[^\"]*)\"", t)})
        for m in re.finditer(r'g5c_router_route\(\s*\w+\s*,\s*"(\w+)"\s*,\s*([^,]+?)\s*,', t):
            path = resolve(m.group(2), defs)
            if path:
                found.add((m.group(1), path))
        if nf == "udm" and p.name == "sdm.c":
            for m in re.finditer(r"add\(\s*r\s*,\s*u\s*,\s*\"(\w+)\"\s*,\s*v\s*,\s*\"([^\"]*)\"", t):
                for ver in ("v1", "v2"):
                    found.add((m.group(1), "/nudm-sdm/%s/{supi}%s" % (ver, m.group(2))))
        if p.name == "api_routes.gen.c":
            for m in re.finditer(r'\{"(GET|PUT|POST|PATCH|DELETE|OPTIONS)",\s*"([^"]+)",\s*"([^"]*)"', t):
                found.add((m.group(1), "/nudr-dr/v2" + m.group(2) if False else m.group(2)))
    return found


def build():
    out = ["# API reference", "",
           "Generated by `tools/docs/gen_api_docs.py` from the sources; do not edit. Every function also serves `GET /health/live`, `GET /health/ready` and `GET /metrics`. The request and response bodies are the "
           "OpenAPI schemas of the TS named per function (pinned under `docs/specs`); errors are `application/problem+json` (TS 29.500 5.2.7). With the cluster defaults every request needs the NRF's "
           "access token (Authorization: Bearer) for the service it addresses and a client certificate (mutual TLS); the admin and northbound APIs have their own authentication (below).", ""]
    total = 0
    for nf, name, desc in NFS:
        rs = sorted(routes_of(nf) - {(m, p) for m, p, _ in COMMON}, key=lambda r: (r[1], r[0]))
        total += len(rs)
        out += ["## %s" % name, "", desc, ""]
        if nf == "udr":
            out += ["The UDR's operations come from the pinned OpenAPI files (generated table `nf/udr/src/api_routes.gen.c`); the path prefix of each API is the service name (`/nudr-dr/v2` and the others of TS 29.504).", ""]
        if nf in ("udm", "pcf"):
            out += ["`/admin/v1/...` is the provisioning API: `Authorization: Bearer <admin token>` (the file named by `admin_token_file`). `g5c-ctl` is its command line.", ""]
        if nf == "scp":
            out += ["The SCP forwards every other path to the producer named by the request (3gpp-Sbi-Target-apiRoot, or discovery parameters: model C and D, TS 29.500 6.10).", ""]
        if nf == "nef":
            out += ["The northbound APIs authenticate the application function with the bearer token configured for it (`nef.afs`).", ""]
        out += ["| Method | Path |", "|---|---|"] + ["| %s | `%s` |" % r for r in rs] + [""]
    out += ["---", "", "%d routes in %d functions." % (total, len(NFS)), ""]
    return "\n".join(out)


def main():
    text = build()
    f = ROOT / "docs" / "api" / "README.md"
    if "--check" in sys.argv:
        if not f.exists() or f.read_text(encoding="utf-8") != text:
            print("api docs: the committed docs/api/README.md differs from the sources (run tools/docs/gen_api_docs.py)")
            return 1
        print("api docs: up to date (%s)" % text.splitlines()[-2])
        return 0
    f.parent.mkdir(parents=True, exist_ok=True)
    f.write_text(text, encoding="utf-8")
    print("wrote", f, text.splitlines()[-2])
    return 0


if __name__ == "__main__":
    sys.exit(main())
