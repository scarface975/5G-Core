#!/usr/bin/env python3
"""Generate the NSSF's schema pool from the pinned TS 29.531 OpenAPI files (Nnssf_NSSelection, Nnssf_NSSAIAvailability).

Output (committed, nf/nssf/src/):
  api_schemas.gen.c   the schemas the NSSF validates against, flattened (tools/oa_pool.py), as pieces of one JSON text
  api_ids.gen.h       NSSF_SCH_* indexes of the schemas the code refers to by name
The operations of the two services are few and written by hand in the C code, from the same files; the generator supplies what is too large
to type: the schemas of the request bodies and of the JSON-encoded query parameters.
Usage: python tools/gen_nssf_api.py [--check]"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from oa_pool import Pool, ROOT  # noqa: E402

OUT = ROOT / "nf" / "nssf" / "src"
SEL = "TS29531_Nnssf_NSSelection.yaml"
AVL = "TS29531_Nnssf_NSSAIAvailability.yaml"
COMMON = "TS29571_CommonData.yaml"

P = Pool({"ts29510nnrfnfmanagement": "TS29510_NRF_NFManagement_Service.yaml"})

# (C name, file, schema) of what the code validates or builds
NAMED = [
    ("SLICE_INFO_REGISTRATION", SEL, "SliceInfoForRegistration"),
    ("SLICE_INFO_PDU_SESSION", SEL, "SliceInfoForPDUSession"),
    ("SLICE_INFO_UE_CU", SEL, "SliceInfoForUEConfigurationUpdate"),
    ("AUTHORIZED_NETWORK_SLICE_INFO", SEL, "AuthorizedNetworkSliceInfo"),
    ("SNSSAI", COMMON, "Snssai"),
    ("PLMN_ID", COMMON, "PlmnId"),
    ("TAI", COMMON, "Tai"),
    ("NSSAI_AVAILABILITY_INFO", AVL, "NssaiAvailabilityInfo"),
    ("AUTHORIZED_NSSAI_AVAILABILITY_INFO", AVL, "AuthorizedNssaiAvailabilityInfo"),
    ("EVENT_SUBSCRIPTION_CREATE", AVL, "NssfEventSubscriptionCreateData"),
    ("EVENT_SUBSCRIPTION_CREATED", AVL, "NssfEventSubscriptionCreatedData"),
    ("EVENT_NOTIFICATION", AVL, "NssfEventNotification"),
    ("PATCH_DOCUMENT", AVL, "PatchDocument"),
]
ids = {name: P.named(f, s) for name, f, s in NAMED}
# the query parameter of the PDN connection procedure is an array of Snssai
arr_ix = len(P.pool)
P.pool.append({"type": "array", "items": {"$": ids["SNSSAI"]}, "minItems": 1})
ids["SNSSAI_ARRAY"] = arr_ix


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


text = json.dumps(P.pool, separators=(",", ":"))
chunks = [text[i:i + 100] for i in range(0, len(text), 100)]
body = ",\n".join("    " + cstr(c) for c in chunks)
gen_c = ("/* Generated by tools/gen_nssf_api.py from the pinned TS 29.531 OpenAPI files. Do not edit. */\n"
         '#include "priv.h"\n\n/* the JSON text of the schema pool in pieces: one literal would exceed the portable limit */\n'
         "const char *const nssf_schema_chunks[] = {\n%s\n};\n\nconst size_t nssf_schema_nchunks = %d;\nconst size_t nssf_schema_count = %d;\n"
         % (body, len(chunks), len(P.pool)))
gen_h = ("/* Generated by tools/gen_nssf_api.py. Do not edit. */\n#ifndef G5C_NSSF_API_IDS_H\n#define G5C_NSSF_API_IDS_H\n\n"
         + "".join("#define NSSF_SCH_%s %d\n" % (k, v) for k, v in ids.items()) + "\n#endif\n")
outputs = {OUT / "api_schemas.gen.c": gen_c, OUT / "api_ids.gen.h": gen_h}

if "--check" in sys.argv:
    bad = [str(p) for p, t in outputs.items() if not p.exists() or p.read_text(encoding="utf8") != t]
    if bad:
        print("stale:", *bad)
        sys.exit(1)
    print("nssf api tables up to date")
else:
    OUT.mkdir(parents=True, exist_ok=True)
    for p, t in outputs.items():
        p.write_text(t, encoding="utf8", newline="\n")
    print(f"{len(P.pool)} schemas ({len(text)} bytes); unresolved refs: {len(P.unresolved)}")
    for u in sorted(P.unresolved):
        print("  unresolved:", u)
