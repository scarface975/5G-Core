#!/usr/bin/env python3
"""Generate the BSF's schema pool from the pinned TS 29.521 OpenAPI file (Nbsf_Management).

Output (committed, nf/bsf/src/):
  api_schemas.gen.c   the schemas the BSF validates against, flattened (tools/spec/oa_pool.py), as pieces of one JSON text
  api_ids.gen.h       BSF_SCH_* indexes of the schemas the code refers to by name
The four operations are written by hand in the C code, from the same file; the generator supplies the schemas of the bodies and of the
query parameters.
Usage: python tools/spec/gen_bsf_api.py [--check]"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from oa_pool import Pool, ROOT  # noqa: E402

OUT = ROOT / "nf" / "bsf" / "src"
BSF = "TS29521_Nbsf_Management.yaml"
COMMON = "TS29571_CommonData.yaml"

P = Pool({"ts29510nnrfnfmanagement": "TS29510_NRF_NFManagement_Service.yaml"})

# (C name, file, schema) of what the code validates or builds
NAMED = [
    ("PCF_BINDING", BSF, "PcfBinding"),
    ("PCF_BINDING_PATCH", BSF, "PcfBindingPatch"),
    ("EXT_PROBLEM_DETAILS", BSF, "ExtProblemDetails"),
    ("SNSSAI", COMMON, "Snssai"),
    ("IPV4_ADDR", COMMON, "Ipv4Addr"),
    ("IPV6_PREFIX", COMMON, "Ipv6Prefix"),
    ("MAC_ADDR48", COMMON, "MacAddr48"),
    ("DNN", COMMON, "Dnn"),
    ("SUPI", COMMON, "Supi"),
    ("GPSI", COMMON, "Gpsi"),
]
ids = {name: P.named(f, s) for name, f, s in NAMED}


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


text = json.dumps(P.pool, separators=(",", ":"))
chunks = [text[i:i + 100] for i in range(0, len(text), 100)]
body = ",\n".join("    " + cstr(c) for c in chunks)
gen_c = ("/* Generated by tools/spec/gen_bsf_api.py from the pinned TS 29.521 OpenAPI file. Do not edit. */\n"
         '#include "priv.h"\n\n/* the JSON text of the schema pool in pieces: one literal would exceed the portable limit */\n'
         "const char *const bsf_schema_chunks[] = {\n%s\n};\n\nconst size_t bsf_schema_nchunks = %d;\nconst size_t bsf_schema_count = %d;\n"
         % (body, len(chunks), len(P.pool)))
gen_h = ("/* Generated by tools/spec/gen_bsf_api.py. Do not edit. */\n#ifndef G5C_BSF_API_IDS_H\n#define G5C_BSF_API_IDS_H\n\n"
         + "".join("#define BSF_SCH_%s %d\n" % (k, v) for k, v in ids.items()) + "\n#endif\n")
outputs = {OUT / "api_schemas.gen.c": gen_c, OUT / "api_ids.gen.h": gen_h}

if "--check" in sys.argv:
    bad = [str(p) for p, t in outputs.items() if not p.exists() or p.read_text(encoding="utf8") != t]
    if bad:
        print("stale:", *bad)
        sys.exit(1)
    print("bsf api tables up to date")
else:
    OUT.mkdir(parents=True, exist_ok=True)
    for p, t in outputs.items():
        p.write_text(t, encoding="utf8", newline="\n")
    print(f"{len(P.pool)} schemas ({len(text)} bytes); unresolved refs: {len(P.unresolved)}")
    for u in sorted(P.unresolved):
        print("  unresolved:", u)
