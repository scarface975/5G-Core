#!/usr/bin/env python3
"""Generate libs/nas/src/defs.c from docs/specs/nas/messages.json (extracted from TS 24.501).

Usage (repo root):
  python tools/spec/extract_nas_tables.py docs/specs/src/24501-g/24501-gf0.docx docs/specs/nas/messages.json
  python tools/spec/gen_nas_defs.py
"""
import json
import re

d = json.load(open("docs/specs/nas/messages.json", encoding="utf8"))


def norm(s):
    return re.sub(r"[^a-z0-9]", "", s.lower())


# --- message type numbers (clause 9.7) -------------------------------------------------------------------
types = {}  # (proto, normalised name) -> value
for tbl in d["message_type_tables"]:
    proto = None
    for row in tbl["rows"]:
        bits = row[:8]
        name = row[-1].strip()
        if not name or not all(b in ("0", "1", "-") for b in bits):
            continue
        if "-" in bits:
            if "mobility" in name:
                proto = "Mm"
            elif "session management" in name:
                proto = "Sm"
            continue
        types[(proto, norm(name))] = int("".join(bits), 2)


def parse_len(s):
    s = s.strip().replace("–", "-")
    if s == "1/2":
        return (1, 1, True)  # half octet
    m = re.match(r"^(\d+)-(\d+|n|x)$", s)
    if m:
        return (int(m.group(1)), 0 if m.group(2) in ("n", "x") else int(m.group(2)), False)
    if s.isdigit():
        return (int(s), int(s), False)
    m = re.match(r"^(\d+)", s)
    return (int(m.group(1)) if m else 0, 0, False)


FORMATS = {"V": "V", "LV": "LV", "LV-E": "LVE", "T": "T", "TV": "TV", "TLV": "TLV", "TLV-E": "TLVE"}
out, missing = [], []
msgs = []
for t in d["messages"]:
    clause = t["clause"]
    if clause.startswith("D."):
        continue  # Annex D: examples for other protocols
    proto = "Sm" if clause.startswith("8.3") else "Mm"
    rows = t["rows"][1:]
    ident = next((i for i, r in enumerate(rows) if "message identity" in r[1].lower()), None)
    if ident is None:
        print("no identity row in", clause, t["message"])
        continue
    name = t["message"] or re.sub(r"\s*message identity$", "", rows[ident][1], flags=re.I)
    if clause == "8.6.27":  # spec typo in the clause number; real message is Security mode reject
        name = "Security mode reject"
    # heading wins when it carries a disambiguating suffix, e.g. "(UE originating de-registration)"
    key = re.sub(r"\s+de-registration\)", ")", name)  # heading says "(UE originating de-registration)"
    mt = types.get((proto, norm(key)))
    if mt is None:
        ident_name = re.sub(r"\s*message identity$", "", rows[ident][1], flags=re.I)
        mt = types.get((proto, norm(ident_name)))
    if mt is None:
        missing.append(name)
        continue
    ies = []
    for r in rows[ident + 1:]:
        if len(r) < 6 or not r[1].strip():
            continue
        iei, ie_name, ref, pres, fmt, length = [c.strip() for c in r[:6]]
        if fmt not in FORMATS or pres not in ("M", "O", "C"):
            print(f"skip row {clause}: {r}")
            continue
        half_iei = iei.endswith("-")
        iei_v = int(iei.rstrip("-"), 16) if iei else None
        ref_clause = re.search(r"(\d+(?:\.\d+)+)\s*$", ref)
        mn, mx, half = parse_len(length)
        ies.append((iei_v, half_iei, ie_name, ref_clause.group(1) if ref_clause else "", pres, FORMATS[fmt], mn, mx, half))
    msgs.append((proto, name, mt, ies))

def cstr(x):
    return '"' + x.replace("\\", "\\\\").replace('"', '\\"') + '"'


w = out.append
w("/* @generated by tools/spec/gen_nas_defs.py from 3GPP TS 24.501 v16.15.0 (docs/specs/nas/messages.json). DO NOT EDIT. */")
w('#include "g5c/nas.h"')
w("")
for i, (proto, name, mt, ies) in enumerate(msgs):
    w(f"static const nas_iedef IES_{i}[] = {{")
    for iei, half_iei, ie_name, ref_clause, pres, fmt, mn, mx, half in ies:
        iei_s = f"0x{iei:02x}" if iei is not None else "-1"
        w(f"    {{{iei_s}, {str(half_iei).lower()}, {cstr(ie_name)}, {cstr(ref_clause)}, NAS_PRES_{pres}, NAS_FMT_{fmt}, {mn}, {mx}, {str(half).lower()}}},")
    if not ies:
        w("    {-1, false, \"\", \"\", NAS_PRES_O, NAS_FMT_V, 0, 0, false}, /* placeholder: no IEs */")
    w("};")
w("")
w("const nas_msgdef NAS_MESSAGES[] = {")
for i, (proto, name, mt, ies) in enumerate(msgs):
    w(f"    {{{cstr(name)}, NAS_PROTO_{proto.upper()}, 0x{mt:02x}, IES_{i}, {len(ies)}}},")
w("};")
w(f"const size_t NAS_NMESSAGES = {len(msgs)};")
open("libs/nas/src/defs.c", "w", encoding="utf8", newline=chr(10)).write(chr(10).join(out) + chr(10))
print(f"{len(msgs)} messages generated; missing type numbers: {missing}")
