#!/usr/bin/env python3
"""Generate the NEF's schema pool from the pinned OpenAPI files (TS 29.522 TrafficInfluence, TS 29.122 MonitoringEvent / AsSessionWithQoS / PfdManagement,
TS 29.514 Npcf_PolicyAuthorization, TS 29.519 application data).

Output (committed, nf/nef/src/):
  api_schemas.gen.c   the schemas the NEF validates against, flattened (tools/spec/oa_pool.py), as pieces of one JSON text
  api_ids.gen.h       NEF_SCH_* indexes of the schemas the code refers to by name
The resources of the northbound APIs are few and written by hand in the C code from the same files; the generator supplies the schemas of the bodies.
Usage: python tools/spec/gen_nef_api.py [--check]"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from oa_pool import Pool, ROOT  # noqa: E402

OUT = ROOT / "nf" / "nef" / "src"
TI = "TS29522_TrafficInfluence.yaml"
ME = "TS29122_MonitoringEvent.yaml"
AQ = "TS29122_AsSessionWithQoS.yaml"
PA = "TS29514_Npcf_PolicyAuthorization.yaml"
PFD = "TS29122_PfdManagement.yaml"
UDRAPP = "TS29519_Unified_Data_Repository_Service_API_file_for_Application_Data.yaml"

P = Pool()

# (C name, file, schema) of what the code validates or builds
NAMED = [
    ("TRAFFIC_INFLU_SUB", TI, "TrafficInfluSub"),
    ("TRAFFIC_INFLU_SUB_PATCH", TI, "TrafficInfluSubPatch"),
    ("TRAFFIC_EVENT_NOTIFICATION", TI, "EventNotification"),
    ("TRAFFIC_AF_ACK_INFO", TI, "AfAckInfo"),
    ("MONITORING_SUBSCRIPTION", ME, "MonitoringEventSubscription"),
    ("MONITORING_NOTIFICATION", ME, "MonitoringNotification"),
    ("AS_QOS_SUBSCRIPTION", AQ, "AsSessionWithQoSSubscription"),
    ("AS_QOS_SUBSCRIPTION_PATCH", AQ, "AsSessionWithQoSSubscriptionPatch"),
    ("AS_QOS_NOTIFICATION", AQ, "UserPlaneNotificationData"),
    ("PFD_MANAGEMENT", PFD, "PfdManagement"),
    ("PFD_DATA", PFD, "PfdData"),
    ("PFD_REPORT", PFD, "PfdReport"),
    ("TEST_NOTIFICATION", "TS29122_CommonData.yaml", "TestNotification"),
    ("APP_SESSION_CONTEXT", PA, "AppSessionContext"),
    ("APP_SESSION_CONTEXT_UPDATE", PA, "AppSessionContextUpdateData"),
    ("EVENTS_NOTIF", PA, "EventsNotification"),
    ("TERMINATION_INFO", PA, "TerminationInfo"),
    ("TRAFFIC_INFLU_DATA", UDRAPP, "TrafficInfluData"),
    ("PROBLEM_DETAILS", "TS29571_CommonData.yaml", "ProblemDetails"),
]
ids = {}
for name, f, s in NAMED:
    try:
        ids[name] = P.named(f, s)
    except KeyError:
        sys.exit(f"schema {s} not found in {f}")


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


text = json.dumps(P.pool, separators=(",", ":"))
chunks = [text[i:i + 100] for i in range(0, len(text), 100)]
body = ",\n".join("    " + cstr(c) for c in chunks)
gen_c = ("/* Generated by tools/spec/gen_nef_api.py from the pinned OpenAPI files. Do not edit. */\n"
         '#include "priv.h"\n\n/* the JSON text of the schema pool in pieces: one literal would exceed the portable limit */\n'
         "const char *const nef_schema_chunks[] = {\n%s\n};\n\nconst size_t nef_schema_nchunks = %d;\nconst size_t nef_schema_count = %d;\n"
         % (body, len(chunks), len(P.pool)))
gen_h = ("/* Generated by tools/spec/gen_nef_api.py. Do not edit. */\n#ifndef G5C_NEF_API_IDS_H\n#define G5C_NEF_API_IDS_H\n\n"
         + "".join("#define NEF_SCH_%s %d\n" % (k, v) for k, v in ids.items()) + "\n#endif\n")
outputs = {OUT / "api_schemas.gen.c": gen_c, OUT / "api_ids.gen.h": gen_h}

if "--check" in sys.argv:
    bad = [str(p) for p, t in outputs.items() if not p.exists() or p.read_text(encoding="utf8") != t]
    if bad:
        print("stale:", *bad)
        sys.exit(1)
    print("nef api tables up to date")
else:
    OUT.mkdir(parents=True, exist_ok=True)
    for p, t in outputs.items():
        p.write_text(t, encoding="utf8", newline="\n")
    print(f"{len(P.pool)} schemas ({len(text)} bytes); unresolved refs: {len(P.unresolved)}")
    for u in sorted(P.unresolved):
        print("  unresolved:", u)
