#!/usr/bin/env python3
"""Embeds deploy/console/index.html in the UDM (nf/udm/src/console_html.h): the page as a byte array and the content security policy that allows exactly its one script and one style
(by SHA-256), nothing external, no framing. `--check` exits 1 when the committed header differs (a ctest runs it).
   python3 tools/gen_console.py [--check]"""
import base64
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "deploy" / "console" / "index.html"
OUT = ROOT / "nf" / "udm" / "src" / "console_html.h"


def build():
    html = SRC.read_bytes().replace(b"\r\n", b"\n")
    text = html.decode("utf-8")
    hashes = []
    for tag in ("script", "style"):
        m = re.findall(r"<%s>(.*?)</%s>" % (tag, tag), text, re.S)
        if len(m) != 1:
            raise SystemExit("gen_console: the page needs exactly one <%s> element" % tag)
        hashes.append((tag, "'sha256-%s'" % base64.b64encode(hashlib.sha256(m[0].encode("utf-8")).digest()).decode()))
    csp = "default-src 'none'; script-src %s; style-src %s; connect-src 'self'; img-src 'none'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'" % (hashes[0][1], hashes[1][1])
    rows = []
    for i in range(0, len(html), 24):
        rows.append("    " + ", ".join("0x%02x" % b for b in html[i:i + 24]) + ",")
    return ("/* SPDX-License-Identifier: LicenseRef-Proprietary */\n/* Generated by tools/gen_console.py from deploy/console/index.html: do not edit. */\n"
            "#ifndef G5C_UDM_CONSOLE_HTML_H\n#define G5C_UDM_CONSOLE_HTML_H\n\nstatic const unsigned char UDM_CONSOLE_HTML[] = {\n%s\n};\n#define UDM_CONSOLE_HTML_LEN %d\n"
            "#define UDM_CONSOLE_CSP \"%s\"\n\n#endif\n" % ("\n".join(rows), len(html), csp))


def main():
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("console: %s differs from deploy/console/index.html (run tools/gen_console.py)" % OUT.relative_to(ROOT))
            return 1
        print("console: up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
