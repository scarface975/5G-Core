#!/usr/bin/env python3
"""Extract the EAP-AKA' test vectors of RFC 9048 Appendix D from the pinned text into libs/crypto/tests/eapaka_vectors.inc (C initialisers).

Usage: python3 tools/gen/gen_eapaka_vectors.py
"""
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent.parent
text = (root / "docs/specs/src/txt/rfc9048.txt").read_text(encoding="utf-8")
start = text.index("Appendix D.  Test Vectors", text.index("Appendix D.  Test Vectors") + 10)
body = text[start:]
cases = re.split(r"\n   Case \d\n", body)[1:]
assert len(cases) == 4, len(cases)


WIDTH = {"AUTN": 32, "IK": 32, "CK": 32, "CK'": 32, "IK'": 32, "K_encr": 32, "K_aut": 64, "K_re": 64, "MSK": 128, "EMSK": 128}


def grab(block, name):
    # "name:" followed by hex groups, continued on the following indented lines that start with a hex group
    m = re.search(r"^\s+" + re.escape(name) + r":\s+(.*?)(?=^\s+[A-Za-z_' ]+:\s|\Z)", block, re.M | re.S)
    assert m, name
    h = re.sub(r"[^0-9a-f]", "", m.group(1).lower())
    return h[:WIDTH[name]]  # the last case is followed by prose, not by another label


out = ["/* generated by tools/gen/gen_eapaka_vectors.py from RFC 9048 Appendix D: do not edit */"]
for c in cases:
    nn = re.search(r'Network name:\s+"(\w+)"', c).group(1)
    ident = re.search(r'Identity:\s+"(\d+)"', c).group(1)
    f = [nn, ident] + [grab(c, k) for k in ("AUTN", "IK", "CK", "CK'", "IK'", "K_encr", "K_aut", "K_re", "MSK", "EMSK")]
    out.append("{" + ", ".join('"%s"' % x for x in f) + "},")
(root / "libs/crypto/tests/eapaka_vectors.inc").write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote", len(cases), "vectors")
