#!/usr/bin/env python3
"""Extract real PFCP messages (Open5GS v2.8.0 SMF <-> UPF) from the golden S3 capture into libs/pfcp/tests/pfcp_vectors.h.

The vectors are behavioural references for the codec and the UPF tests, never source code. Regenerate after replacing the capture:
    python3 tools/gen/gen_pfcp_vectors.py"""
import importlib.util
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
spec = importlib.util.spec_from_file_location("gd", str(ROOT / "tools" / "docs" / "gen_dashboard.py"))
gd = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gd)

WANT = [  # (name, message type, occurrence index among messages of that type, from the SMF side?)
    ("ASSOC_SETUP_REQ", 5, 0), ("ASSOC_SETUP_RSP", 6, 0), ("SESS_EST_REQ", 50, 0), ("SESS_EST_RSP", 51, 0),
    ("SESS_MOD_REQ", 52, 0), ("SESS_MOD_RSP", 53, 0), ("SESS_DEL_REQ", 54, 0), ("SESS_DEL_RSP", 55, 0),
]
found = {}
count = {}
for _ts, ip in gd.read_pcapng(ROOT / "tests/fixtures/golden/s3_open5gs_v2.8.0_ueransim.pcapng"):
    p = gd.parse_ip(ip)
    if not p or p[0] != 17:
        continue
    sport, dport = struct.unpack_from(">HH", p[3], 0)
    if 8805 not in (sport, dport):
        continue
    ud = bytes(p[3][8:])
    mt = ud[1]
    n = count.get(mt, 0)
    count[mt] = n + 1
    for name, t, idx in WANT:
        if t == mt and idx == n:
            found[name] = ud
out = ["/* SPDX-License-Identifier: LicenseRef-Proprietary */",
       "/* Generated by tools/gen/gen_pfcp_vectors.py from tests/fixtures/golden/s3_open5gs_v2.8.0_ueransim.pcapng. Do not edit. */",
       "#ifndef G5C_PFCP_VECTORS_H", "#define G5C_PFCP_VECTORS_H", ""]
for name, _t, _i in WANT:
    out.append('#define PFCPV_%s "%s"' % (name, found[name].hex()))
out += ["", "#endif", ""]
(ROOT / "libs/pfcp/tests/pfcp_vectors.h").write_text("\n".join(out), encoding="utf8", newline="\n")
print({k: len(v) for k, v in found.items()})
