#!/usr/bin/env python3
"""Generate libs/crypto/tests/milenage_vectors.h from the 20 test sets of TS 35.208 (text extracted with
tools/spec/doc_to_text.py to docs/specs/src/35208-g00.txt). Used by libs/crypto/tests/test_milenage.c."""
import re

text = open("docs/specs/src/35208-g00.txt", encoding="utf8").read()
sets = {}
# each set has a "Hexadecimal"/"Variable | Value" table row; sets 2..20 start at "4.3.N Test Set N"
for m in re.finditer(r"4\.3\.(\d+)\t(?:Set|Test Set) \d+\n(.*?)(?=\n4\.3\.\d+\t|\Z)", text, flags=re.S):
    n = int(m.group(1))
    body = m.group(2)
    if "Hexadecimal Format" in body:
        body = body.split("Hexadecimal Format", 1)[1]
    flat = body.replace("\n", "").replace("\t", "|")
    vals = {}
    for key in ("K", "RAND", "SQN", "AMF", "OP", "OPC", "f1", "f1\\*", "f2", "f3", "f4", "f5", "f5\\*"):
        mm = re.search(r"\|\|?" + key + r"\|([0-9a-fA-F ]+?)(?=\|)", flat) or re.search(r"(?:^|\|)" + key + r"\|([0-9a-fA-F ]+?)(?=\||$)", flat)
        if mm:
            vals[key.replace("\\", "")] = mm.group(1).replace(" ", "").lower()
    sets[n] = vals

need = ["K", "RAND", "SQN", "AMF", "OP", "OPC", "f1", "f1*", "f2", "f3", "f4", "f5", "f5*"]
bad = {n: [k for k in need if k not in v] for n, v in sets.items() if any(k not in v for k in need)}
assert len(sets) == 20 and not bad, (sorted(sets), bad)

out = ["/* @generated by tools/gen/gen_milenage_vectors.py from 3GPP TS 35.208 v16.0.0 clause 4.3. DO NOT EDIT. */",
       "/* field order: K, RAND, SQN, AMF, OP, OPc, f1, f1*, f2, f3, f4, f5, f5* */",
       "typedef struct { const char *v[13]; } ms_set;",
       "static const ms_set SETS[] = {"]
for n in range(1, 21):
    v = sets[n]
    row = [v[k] for k in ("K", "RAND", "SQN", "AMF", "OP", "OPC", "f1", "f1*", "f2", "f3", "f4", "f5", "f5*")]
    out.append("    {{" + ", ".join(f'"{x}"' for x in row) + "}},")
out.append("};")
open("libs/crypto/tests/milenage_vectors.h", "w", encoding="utf8", newline="\n").write("\n".join(out) + "\n")
print("generated 20 sets")
