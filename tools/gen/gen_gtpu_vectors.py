#!/usr/bin/env python3
"""Extract real GTP-U G-PDUs (UERANSIM gNB <-> Open5GS UPF, ICMP echo through the user plane) from the golden S3 capture into
nf/upf/tests/gtpu_vectors.h: the first uplink and downlink packet. Behavioural references only.
    python3 tools/gen/gen_gtpu_vectors.py"""
import importlib.util
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
spec = importlib.util.spec_from_file_location("gd", str(ROOT / "tools" / "docs" / "gen_dashboard.py"))
gd = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gd)

ul = dl = None
for _ts, ip in gd.read_pcapng(ROOT / "tests/fixtures/golden/s3_open5gs_v2.8.0_ueransim.pcapng"):
    p = gd.parse_ip(ip)
    if not p or p[0] != 17:
        continue
    sport, dport = struct.unpack_from(">HH", p[3], 0)
    if 2152 not in (sport, dport):
        continue
    ud = bytes(p[3][8:])
    if len(ud) < 12 or ud[1] != 255:
        continue
    inner_ver = None
    flags = ud[0]
    off = 8 + (4 if flags & 7 else 0)
    if flags & 4:  # extension headers
        nxt = ud[11]
        while nxt and off < len(ud):
            ln = ud[off] * 4
            nxt = ud[off + ln - 1]
            off += ln
    inner = ud[off:]
    if inner and inner[0] >> 4 == 4 and inner[9] == 1:  # IPv4 ICMP
        icmp_type = inner[(inner[0] & 15) * 4]
        if icmp_type == 8 and ul is None:
            ul = ud
        elif icmp_type == 0 and dl is None:
            dl = ud
    if ul and dl:
        break
assert ul and dl, "no ICMP echo found in the capture"
out = ["/* SPDX-License-Identifier: LicenseRef-Proprietary */",
       "/* Generated by tools/gen/gen_gtpu_vectors.py from tests/fixtures/golden/s3_open5gs_v2.8.0_ueransim.pcapng. Do not edit. */",
       "#ifndef G5C_GTPU_VECTORS_H", "#define G5C_GTPU_VECTORS_H", "",
       "/* an uplink G-PDU from the gNB (ICMP echo request from the UE) and a downlink G-PDU from the UPF (the echo reply) */",
       '#define GTPUV_UL "%s"' % ul.hex(), '#define GTPUV_DL "%s"' % dl.hex(), "", "#endif", ""]
(ROOT / "nf/upf/tests/gtpu_vectors.h").write_text("\n".join(out), encoding="utf8", newline="\n")
print("ul %d bytes, dl %d bytes; dl header %s" % (len(ul), len(dl), dl[:16].hex()))
