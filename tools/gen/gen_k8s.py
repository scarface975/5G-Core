#!/usr/bin/env python3
"""deploy/k8s/base: Kubernetes manifests generated from the compose model (deploy/compose/compose.yaml and its config/*.yaml), so the two cannot drift (backlog F-04).
   python3 tools/gen/gen_k8s.py [--check]
One namespace; per function a ConfigMap (its configuration), a Deployment (restricted pod security: non-root, read-only root, no capabilities, seccomp), a Service on its SBI port, a claim for its
state directory; the AMF's N2 as an SCTP port, the UPF's N3 and N4 as UDP; secrets are referenced from one Secret `g5c-secrets` that the operator creates (never generated here); default-deny
network policies with the allowances the core needs. NEVER APPLIED: there is no cluster in this repository's test environment. `tests/support/test_k8s.py` cross-checks every reference."""
import os
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
COMPOSE = os.path.join(ROOT, "deploy", "compose", "compose.yaml")
CONF = os.path.join(ROOT, "deploy", "compose", "config")
OUT = os.path.join(ROOT, "deploy", "k8s", "base")
NS = "g5c"
# the addresses of the compose network that the sample configurations name; a pod has none of them. Each is rendered when the pod starts: a function's own address becomes its pod IP,
# a peer's becomes the address of the peer's Service. The compose network as a whole (an allow-list in the SCP) is opened: the network policies confine the traffic.
IPMAP = {"10.100.0.4": "smf", "10.100.0.5": "amf", "10.100.0.7": "upf"}
CIDR = "10.100.0.0/24"
HEADER = "# Generated by tools/gen/gen_k8s.py from deploy/compose: do not edit. Never applied to a cluster.\n"


def _str(dumper, data):
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|" if "\n" in data else None)


yaml.add_representer(str, _str, Dumper=yaml.SafeDumper)


def version():
    return open(os.path.join(ROOT, "VERSION")).read().strip()


def labels(nf):
    return {"app.kubernetes.io/name": nf, "app.kubernetes.io/part-of": "g5c"}


def sbi_port(nf):
    c = yaml.safe_load(open(os.path.join(CONF, nf + ".yaml")))
    return int(c["sbi"]["port"])


def build():
    comp = yaml.safe_load(open(COMPOSE))
    docs = {"namespace.yaml": [{"apiVersion": "v1", "kind": "Namespace", "metadata": {"name": NS, "labels": {"pod-security.kubernetes.io/enforce": "baseline", "pod-security.kubernetes.io/warn": "restricted"}}}]}
    image = "g5c:" + version()
    nfs = sorted(comp["services"])
    for nf in nfs:
        svc = comp["services"][nf]
        port = sbi_port(nf)
        cfg = "\n".join(l.rstrip().replace("\t", "    ") for l in open(os.path.join(CONF, nf + ".yaml")).read().splitlines()) + "\n"  # block-literal friendly
        literal = sorted(ip for ip in IPMAP if ip in cfg) + ([CIDR] if CIDR in cfg else [])
        vols = [{"name": "config", "configMap": {"name": nf + "-config"}}]
        if literal:  # rendered at pod start into /rendered, read by the function from there
            mounts = [{"name": "rendered", "mountPath": "/etc/g5c-rendered", "readOnly": True}]
            vols.append({"name": "rendered", "emptyDir": {}})
        else:
            mounts = [{"name": "config", "mountPath": "/etc/g5c/%s.yaml" % nf, "subPath": nf + ".yaml", "readOnly": True}]
        secret_items = []
        data_dir = False
        for v in svc.get("volumes", []):
            src, dst = v.split(":")[0], v.split(":")[1]
            if src.startswith("./secrets/") or src.startswith("./keys/"):
                key = os.path.basename(src)
                secret_items.append({"key": key, "path": os.path.basename(dst)})
            elif src.endswith("-data"):
                data_dir = True
            elif src.endswith("-keys"):
                data_dir = True
        if secret_items:
            vols.append({"name": "secrets", "secret": {"secretName": "g5c-secrets", "items": secret_items, "defaultMode": 0o400}})
            mounts.append({"name": "secrets", "mountPath": "/etc/g5c/keys", "readOnly": True})
        if data_dir:
            vols.append({"name": "state", "persistentVolumeClaim": {"claimName": nf + "-state"}})
            mounts.append({"name": "state", "mountPath": "/var/lib/g5c"})
        vols.append({"name": "tmp", "emptyDir": {}})
        mounts.append({"name": "tmp", "mountPath": "/tmp"})
        sc = {"allowPrivilegeEscalation": False, "readOnlyRootFilesystem": True, "runAsNonRoot": True, "capabilities": {"drop": ["ALL"]}, "seccompProfile": {"type": "RuntimeDefault"}}
        ports = [{"name": "sbi", "containerPort": port, "protocol": "TCP"}]
        sports = [{"name": "sbi", "port": port, "targetPort": "sbi", "protocol": "TCP"}]
        if nf == "amf":
            ports.append({"name": "n2", "containerPort": 38412, "protocol": "SCTP"})
            sports.append({"name": "n2", "port": 38412, "targetPort": "n2", "protocol": "SCTP"})
        if nf == "upf":
            ports += [{"name": "n3", "containerPort": 2152, "protocol": "UDP"}, {"name": "n4", "containerPort": 8805, "protocol": "UDP"}]
            sports += [{"name": "n3", "port": 2152, "targetPort": "n3", "protocol": "UDP"}, {"name": "n4", "port": 8805, "targetPort": "n4", "protocol": "UDP"}]
            sc["capabilities"] = {"drop": ["ALL"], "add": ["NET_ADMIN"]}  # the TUN device of N6
            vols.append({"name": "tun", "hostPath": {"path": "/dev/net/tun", "type": "CharDevice"}})
            mounts.append({"name": "tun", "mountPath": "/dev/net/tun"})
        container = {"name": nf, "image": image, "imagePullPolicy": "IfNotPresent", "args": [nf, ("/etc/g5c-rendered/%s.yaml" if literal else "/etc/g5c/%s.yaml") % nf], "ports": ports, "securityContext": sc,
                     "volumeMounts": mounts, "resources": {"requests": {"cpu": "100m", "memory": "128Mi"}, "limits": {"memory": "1Gi"}},
                     # the sample configurations serve cleartext HTTP/2, which an HTTP/1.1 probe of the kubelet cannot speak: the probes are TCP-level (with sbi.tls set, use httpGet probes)
                     "livenessProbe": {"tcpSocket": {"port": "sbi"}, "periodSeconds": 10, "failureThreshold": 3},
                     "readinessProbe": {"tcpSocket": {"port": "sbi"}, "periodSeconds": 5, "failureThreshold": 3}}
        pod = {"metadata": {"labels": labels(nf)}, "spec": {"securityContext": {"runAsNonRoot": True, "runAsUser": 10001, "runAsGroup": 10001, "fsGroup": 10001, "seccompProfile": {"type": "RuntimeDefault"}},
                                                            "automountServiceAccountToken": False, "containers": [container], "volumes": vols}}
        if literal:
            lookups, subs = [], []
            for ip in literal:
                if ip == CIDR:
                    subs.append("-e 's#%s#0.0.0.0/0#g'" % CIDR.replace(".", "\\."))
                    continue
                peer = IPMAP[ip]
                val = "$POD_IP" if peer == nf else "$(getent hosts %s | cut -d' ' -f1)" % peer
                lookups.append(("until [ -n \"%s\" ]; do sleep 1; done" % val) if peer != nf else "")
                subs.append("-e \"s/%s/%s/g\"" % (ip.replace(".", "\\."), val))
            script = "set -eu; " + "".join(x + "; " for x in lookups if x) + "sed %s /config-src/%s.yaml > /rendered/%s.yaml" % (" ".join(subs), nf, nf)
            init = {"name": "render-config", "image": image, "imagePullPolicy": "IfNotPresent", "command": ["/bin/sh", "-c", script],
                    "env": [{"name": "POD_IP", "valueFrom": {"fieldRef": {"fieldPath": "status.podIP"}}}],
                    "securityContext": {"allowPrivilegeEscalation": False, "readOnlyRootFilesystem": True, "runAsNonRoot": True, "capabilities": {"drop": ["ALL"]}, "seccompProfile": {"type": "RuntimeDefault"}},
                    "volumeMounts": [{"name": "config", "mountPath": "/config-src", "readOnly": True}, {"name": "rendered", "mountPath": "/rendered"}]}
            pod["spec"]["initContainers"] = [init]
        deploy = {"apiVersion": "apps/v1", "kind": "Deployment", "metadata": {"name": nf, "namespace": NS, "labels": labels(nf)},
                  "spec": {"replicas": 1, "strategy": {"type": "Recreate"}, "selector": {"matchLabels": {"app.kubernetes.io/name": nf}}, "template": pod}}
        service = {"apiVersion": "v1", "kind": "Service", "metadata": {"name": nf, "namespace": NS, "labels": labels(nf)}, "spec": {"selector": {"app.kubernetes.io/name": nf}, "ports": sports}}
        cm = {"apiVersion": "v1", "kind": "ConfigMap", "metadata": {"name": nf + "-config", "namespace": NS, "labels": labels(nf)}, "data": {nf + ".yaml": cfg}}
        parts = [cm, deploy, service]
        if data_dir:
            parts.insert(1, {"apiVersion": "v1", "kind": "PersistentVolumeClaim", "metadata": {"name": nf + "-state", "namespace": NS, "labels": labels(nf)},
                             "spec": {"accessModes": ["ReadWriteOnce"], "resources": {"requests": {"storage": "1Gi"}}}})
        docs[nf + ".yaml"] = parts
    docs["networkpolicy.yaml"] = [
        {"apiVersion": "networking.k8s.io/v1", "kind": "NetworkPolicy", "metadata": {"name": "default-deny", "namespace": NS}, "spec": {"podSelector": {}, "policyTypes": ["Ingress", "Egress"]}},
        {"apiVersion": "networking.k8s.io/v1", "kind": "NetworkPolicy", "metadata": {"name": "allow-inside-the-core", "namespace": NS},
         "spec": {"podSelector": {}, "policyTypes": ["Ingress", "Egress"], "ingress": [{"from": [{"podSelector": {}}]}], "egress": [{"to": [{"podSelector": {}}]}, {"ports": [{"port": 53, "protocol": "UDP"}, {"port": 53, "protocol": "TCP"}]}]}},
        {"apiVersion": "networking.k8s.io/v1", "kind": "NetworkPolicy", "metadata": {"name": "allow-n2-from-gnbs", "namespace": NS},
         "spec": {"podSelector": {"matchLabels": {"app.kubernetes.io/name": "amf"}}, "policyTypes": ["Ingress"], "ingress": [{"ports": [{"port": 38412, "protocol": "SCTP"}]}]}},
        {"apiVersion": "networking.k8s.io/v1", "kind": "NetworkPolicy", "metadata": {"name": "allow-n3-from-gnbs", "namespace": NS},
         "spec": {"podSelector": {"matchLabels": {"app.kubernetes.io/name": "upf"}}, "policyTypes": ["Ingress"], "ingress": [{"ports": [{"port": 2152, "protocol": "UDP"}]}]}},
    ]
    docs["kustomization.yaml"] = [{"apiVersion": "kustomize.config.k8s.io/v1beta1", "kind": "Kustomization", "namespace": NS,
                                   "resources": ["namespace.yaml"] + [n + ".yaml" for n in nfs] + ["networkpolicy.yaml"], "images": [{"name": "g5c", "newName": "g5c", "newTag": version()}]}]
    return docs


def render(docs):
    out = {}
    for name, parts in docs.items():
        out[name] = HEADER + "---\n".join(yaml.safe_dump(p, sort_keys=False, default_flow_style=False) for p in parts)
    return out


def main():
    files = render(build())
    if "--check" in sys.argv:
        bad = [n for n, t in files.items() if not os.path.exists(os.path.join(OUT, n)) or open(os.path.join(OUT, n), encoding="utf-8").read() != t]
        if bad:
            print("deploy/k8s/base is stale (%s): run python3 tools/gen/gen_k8s.py" % ", ".join(bad))
            return 1
        print("k8s: fresh")
        return 0
    os.makedirs(OUT, exist_ok=True)
    for n, t in files.items():
        open(os.path.join(OUT, n), "w", encoding="utf-8", newline="\n").write(t)
    print("wrote %d files to %s" % (len(files), OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
